"""Build the active Phase 4 IAM execution/review manifest.

Only named-profile execution documents are active. Optional OIDC documents are
recorded separately as excluded future proposals. The builder never verifies for
execution; execution paths load and verify the independently reviewed manifest.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

from phase4_iam_manifest_schema import SCHEMA, validate_manifest

REPO = Path(__file__).resolve().parents[1]
RENDERED = REPO / "var" / "phase4" / "iam"
PRIVATE_MANIFEST = RENDERED / "active-manifest.json"
PUBLIC_MANIFEST = REPO / "docs" / "delivery-recovery" / "phase4-active-iam-manifest.json"
TERRAFORM_MAIN = REPO / "infra" / "terraform" / "main.tf"

ACTIVE = {
    "bootstrap-trust-policy.json": "cli-initial-human",
    "bootstrap-policy.json": "cli-initial-human",
    "deploy-named-profile-trust-policy.json": "cli-bootstrap-role",
    "deploy-policy.json": "cli-bootstrap-role",
    "operator-trust-policy.json": "cli-bootstrap-role",
    "operator-policy.json": "cli-bootstrap-role",
    "runtime-trust-policy.json": "terraform-runtime-reference",
    "runtime-policy.json": "terraform-runtime-reference",
    "runtime-boundary-policy.json": "terraform-runtime",
}
EXCLUDED_OIDC = (
    "deploy-trust-policy.json",
    "github-oidc-trust-policy.json",
)
PLACEHOLDERS = (
    "<account-id>",
    "<bootstrap-principal-arn>",
    "<deployer-principal-arn>",
    "<operator-principal-arn>",
)


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_manifest(
    rendered_dir: Path,
    terraform_main: Path,
    previous_manifest: Path | None = None,
) -> dict:
    missing = [name for name in ACTIVE if not (rendered_dir / name).is_file()]
    if missing:
        raise SystemExit(f"missing rendered documents: {missing}")
    entries = {}
    for name, owner in ACTIVE.items():
        path = rendered_dir / name
        text = path.read_text(encoding="utf-8")
        if any(placeholder in text for placeholder in PLACEHOLDERS):
            raise SystemExit(f"unresolved placeholder in {name}")
        json.loads(text)
        entries[name] = {
            "sha256": _digest(path),
            "bytes": path.stat().st_size,
            "applied_by": owner,
        }
    excluded = {
        name: {
            "sha256": _digest(rendered_dir / name),
            "reason": "optional OIDC; not in active named-profile path",
        }
        for name in EXCLUDED_OIDC
        if (rendered_dir / name).is_file()
    }
    carried_validation = None
    if previous_manifest is not None and previous_manifest.is_file():
        try:
            previous = json.loads(previous_manifest.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            previous = {}
        if previous.get("active_documents") == entries:
            validation = previous.get("validation")
            if isinstance(validation, dict):
                carried_validation = validation
    document = {
        "schema": SCHEMA,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "active_document_count": len(entries),
        "excluded_optional_oidc_count": len(excluded),
        "active_documents": entries,
        "excluded_optional_oidc": excluded,
        "terraform_generated_source": {
            "path": "infra/terraform/main.tf",
            "sha256": _digest(terraform_main),
            "covers": ["runtime trust policy", "runtime inline logs policy"],
        },
        "notes": [
            "Hashes are of actual rendered private documents; public manifest contains no account/ARN values.",
            "Runtime trust and inline logs are generated by Terraform; runtime-trust-policy.json and runtime-policy.json are review references.",
            "Changed rendered bytes lose prior independent review and require re-review.",
        ],
    }
    if carried_validation is not None:
        document["validation"] = carried_validation
    return validate_manifest(document)


def main() -> int:
    document = build_manifest(RENDERED, TERRAFORM_MAIN, PRIVATE_MANIFEST)
    PRIVATE_MANIFEST.write_text(
        json.dumps(document, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    PUBLIC_MANIFEST.write_text(
        json.dumps(document, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(
        json.dumps(
            {
                "schema": document["schema"],
                "active_document_count": document["active_document_count"],
                "excluded_optional_oidc_count": document["excluded_optional_oidc_count"],
                "private_manifest": str(PRIVATE_MANIFEST.relative_to(REPO)),
                "public_manifest": str(PUBLIC_MANIFEST.relative_to(REPO)),
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
