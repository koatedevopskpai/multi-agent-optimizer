"""Eval gate: run the CPM engine against golden cases and assert correctness.

Usage:  python evals/evaluate.py
Exit code 0 on pass, 1 on any mismatch. Writes evals/EVAL_REPORT.md.
"""

from __future__ import annotations

import json
import pathlib
import sys

from multi_agent_optimizer import ProjectError, schedule

REPO = pathlib.Path(__file__).resolve().parents[1]
GOLDEN_DIR = pathlib.Path(__file__).parent / "golden_cases"
REPORT = pathlib.Path(__file__).parent / "EVAL_REPORT.md"


def main() -> int:
    failures: list[str] = []
    rows: list[str] = []

    for path in sorted(GOLDEN_DIR.glob("*.json")):
        case = json.loads(path.read_text(encoding="utf-8"))
        try:
            plan = schedule(case["project"])
        except ProjectError as exc:
            failures.append(f"{path.name}: engine raised: {exc}")
            continue

        expected = case["expected"]
        actual_duration = plan.project_duration
        actual_critical = sorted(plan.critical_path)
        exp_duration = expected["project_duration"]
        exp_critical = sorted(expected["critical_path"])

        ok = actual_duration == exp_duration and actual_critical == exp_critical
        rows.append(
            f"| {case['name']} | {exp_duration} | {actual_duration} | "
            f"{','.join(exp_critical)} | {','.join(actual_critical)} | {'PASS' if ok else 'FAIL'} |"
        )
        if not ok:
            failures.append(
                f"{path.name}: expected duration {exp_duration} got {actual_duration}; "
                f"expected critical {exp_critical} got {actual_critical}"
            )

    lines = [
        "# Evaluation report",
        "",
        f"_Generated by `python evals/evaluate.py` — model: deterministic CPM. {len(rows)} case(s)._",
        "",
        "| Case | Expected dur | Actual dur | Expected critical | Actual critical | Result |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        *([] if failures else ["**All golden cases pass.**"]),
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if failures:
        print("EVAL FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"ALL golden cases pass ({len(rows)} cases). Report saved -> {REPORT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())